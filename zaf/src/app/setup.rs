//! `zaf setup`: make the two homes, fetch the design repo, run doctor, hand over what is left.
//!
//! It never installs a tool: every tool doctor reports as missing, too old or
//! unknown becomes a [`Fix`] for the Engineer (see [`fixes`]). Running it again
//! changes nothing that is already in place.
//!
//! The folders are [`ensure_homes`]: the project's `.zaf/` and the zaf home, created when
//! missing and never rewritten. Every other verb runs it first; only an explicit `setup`
//! goes further and replaces an old `.zaf/.gitignore` that holds just `*`.
//!
//! A root `ZAF.toml` is renamed to `.zaf.toml` by [`move_legacy_manifest`], and only here:
//! `setup` outside an instance. Every other verb reads the old name and warns.
//!
//! The manifest's profiles are generated by [`profile::init_with`], the generation `zaf profile
//! init` runs, after the homes and the design clone and before doctor; it links each profile's
//! login to the Claude home's. A rerun with nothing changed writes nothing and issues no plugin
//! command. A refusal (the pack at another version than its tag) is a fix; a failed
//! backend is a [`SetupError`].
//!
//! After the profiles, [`install_pack_actions`] copies the `actions/` folder of the pack installed
//! in a generated profile into the zaf home's `actions/`: each file the machine tier lacks, with
//! its mode bits, once. A name already there is left byte for byte, and nothing is deleted, unless
//! it is a regular file that differs from the pack's and a [`ReplaceAction`] asker says yes: the old
//! file is then kept under `actions-replaced/` in the zaf home and the pack's renamed into place.

