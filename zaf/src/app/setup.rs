/// The folders under the project's `.zaf/` that `setup` makes.
pub const PROJECT_DIRS: [&str; 3] = ["actions", "roles", "logs"];
/// The folders under the zaf home that `setup` makes.
pub const HOME_DIRS: [&str; 1] = ["actions"];
/// The file in `.zaf/` that keeps the machine's state out of version control.
pub const IGNORE_FILE: &str = ".gitignore";
/// The lines of `.zaf/.gitignore`: an allow-list, so actions and roles stay tracked.
pub const IGNORE_LINES: [&str; 7] = [
    "*",
    "!.gitignore",
    "!config.toml",
    "!actions/",
    "!actions/**",
    "!roles/",
    "!roles/**",
];
/// The zaf home's `config.toml` when `setup` makes it: every line a comment.
pub const HOME_CONFIG: &str = "\
# zaf machine config: defaults every project on this machine inherits.
# A project's .zaf.toml and .zaf/config.toml sit above this file and win, property by
# property; an array is replaced whole, never merged. Everything here is commented out.
#
# [actions]
# timeout_minutes = 30
";

/// What `.zaf/.gitignore` held when the homes were ensured.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IgnoreState {
    /// It was absent and the allow-list was written.
    Written,
    /// It already is the allow-list.
    Current,
    /// It holds only `*`, the old file: [`ensure_homes`] leaves it, `setup` replaces it.
    Star,
    /// It holds anything else: kept, and the Engineer merges the allow-list by hand.
    Foreign,
    /// It held only `*` and `setup` replaced it with the allow-list.
    Replaced,
}

/// What [`ensure_homes`] found and made.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Homes {
    /// Every folder and file it created, in order; empty when both homes were complete.
    pub made: Vec<PathBuf>,
    /// The homes where something was made, for the one line a verb prints.
    pub touched: Vec<PathBuf>,
    /// The state of the project's `.zaf/.gitignore`; `None` outside a project.
    pub ignore: Option<IgnoreState>,
}

impl Homes {
    /// The one line a verb prints on stderr when it made something; `None` when it made nothing.
    pub fn notice(&self) -> Option<String> {
        if self.made.is_empty() {
            return None;
        }
        let places: Vec<String> = self
            .touched
            .iter()
            .map(|path| path.display().to_string())
            .collect();
        Some(format!(
            "zaf: made what was missing in {}",
            places.join(", ")
        ))
    }
}

/// Creates what is missing of the project's `.zaf/` (under `root`, when in a project) and of the
/// zaf `home` (when there is one): the folders, the commented `config.toml` and the
/// allow-list `.gitignore`. Anything already there is left exactly as it is, an old
/// `.gitignore` included; no doctor, no clone, no fixes.
pub fn ensure_homes(root: Option<&Path>, home: Option<&Path>) -> io::Result<Homes> {
    let mut homes = Homes::default();
    if let Some(root) = root {
        let state = root.join(STATE_DIR);
        let before = homes.made.len();
        for dir in PROJECT_DIRS {
            make_dir(&state.join(dir), &mut homes.made)?;
        }
        let ignore = state.join(IGNORE_FILE);
        homes.ignore = Some(if make_file(&ignore, &ignore_text(), &mut homes.made)? {
            IgnoreState::Written
        } else {
            classify_ignore(&ignore)?
        });
        if homes.made.len() > before {
            homes.touched.push(state);
        }
    }
    if let Some(home) = home {
        let before = homes.made.len();
        make_dir(home, &mut homes.made)?;
        for dir in HOME_DIRS {
            make_dir(&home.join(dir), &mut homes.made)?;
        }
        make_file(&home.join(HOME_FILE), HOME_CONFIG, &mut homes.made)?;
        if homes.made.len() > before {
            homes.touched.push(home.to_owned());
        }
    }
    Ok(homes)
}

fn ignore_text() -> String {
    let mut text = IGNORE_LINES.join("\n");
    text.push('\n');
    text
}

fn make_dir(path: &Path, made: &mut Vec<PathBuf>) -> io::Result<()> {
    if !path.is_dir() {
        fs::create_dir_all(path)?;
        made.push(path.to_owned());
    }
    Ok(())
}

/// Writes `text` to `path` unless a file is there; whether it wrote.
fn make_file(path: &Path, text: &str, made: &mut Vec<PathBuf>) -> io::Result<bool> {
    match OpenOptions::new().write(true).create_new(true).open(path) {
        Ok(mut file) => {
            file.write_all(text.as_bytes())?;
            made.push(path.to_owned());
            Ok(true)
        }
        Err(error) if error.kind() == io::ErrorKind::AlreadyExists => Ok(false),
        Err(error) => Err(error),
    }
}

fn classify_ignore(path: &Path) -> io::Result<IgnoreState> {
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(error) if error.kind() == io::ErrorKind::InvalidData => {
            return Ok(IgnoreState::Foreign);
        }
        Err(error) => return Err(error),
    };
    let lines: Vec<&str> = text.lines().map(str::trim).collect();
    Ok(if lines == IGNORE_LINES {
        IgnoreState::Current
    } else if lines == ["*"] {
        IgnoreState::Star
    } else {
        IgnoreState::Foreign
    })
}

/// Whether the project's own `.gitignore` ignores the `.zaf/` folder itself; git cannot
/// re-include a file under an ignored folder, so the allow-list would do nothing.
pub fn root_ignores_state_dir(root: &Path) -> bool {
    let Ok(text) = fs::read_to_string(root.join(".gitignore")) else {
        return false;
    };
    text.lines().map(str::trim).any(|line| {
        matches!(
            line,
            ".zaf" | ".zaf/" | "/.zaf" | "/.zaf/" | "**/.zaf" | "**/.zaf/"
        )
    })
}

/// What [`move_legacy_manifest`] did with a root `ZAF.toml`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LegacyMove {
    /// There is no root `ZAF.toml`: nothing to move.
    Absent,
    /// It was renamed to `.zaf.toml`.
    Moved,
    /// It is there, and an instance does not move it: the move is the Engineer's.
    ForEngineer,
}

impl LegacyMove {
    /// The one line `setup` prints about the move; `None` when there was nothing to say.
    pub fn line(self) -> Option<String> {
        match self {
            Self::Absent => None,
            Self::Moved => Some(format!("moved {LEGACY_FILE} to {ROOT_FILE}")),
            Self::ForEngineer => Some(format!(
                "{LEGACY_FILE} stays: moving it to {ROOT_FILE} is for the Engineer, who runs `zaf setup` outside an instance"
            )),
        }
    }
}

/// Renames the project's root `ZAF.toml` to `.zaf.toml`, but only for the Engineer: with
/// `as_instance` set (a `ZAF_INSTANCE` run) it moves nothing and says so. The only place
/// that moves the file; every other verb reads it. A `ZAF.toml` beside `.zaf.toml` or
/// `.zaf/config.toml` is refused as the manifest layers refuse it, naming both, and nothing
/// moves. A second call finds nothing to move.
pub fn move_legacy_manifest(
    root: &Path,
    home: Option<&Path>,
    as_instance: bool,
) -> io::Result<LegacyMove> {
    let files = ProjectFiles::find(root, home);
    let Some(legacy) = &files.legacy else {
        return Ok(LegacyMove::Absent);
    };
    files
        .refuse_legacy_beside_new()
        .map_err(|error| io::Error::new(io::ErrorKind::AlreadyExists, error.to_string()))?;
    if as_instance {
        return Ok(LegacyMove::ForEngineer);
    }
    fs::rename(legacy, root.join(ROOT_FILE))?;
    Ok(LegacyMove::Moved)
}

/// The verbs of a plan row that write into the project or the homes: a plan with none of them
/// changes nothing and is run without a question.
const WRITING_VERBS: [&str; 4] = ["Ask", "Write", "Move", "Make"];

/// What this run of `setup` will do, worked out from what is there; nothing is written.
///
/// The rows, in order: "Ask n questions" and "Write .zaf.toml" only with no manifest of any
/// name (n is init's question list for this folder); "Move ZAF.toml to .zaf.toml" for a
/// lone legacy manifest, and only outside an instance (`as_instance`), which never moves it;
/// "Make" only for the project's `.zaf/` and the zaf `home` that are missing something
/// (`~/.zaf and .zaf/` when both are); then always "Install the standard actions" and "Check your
/// tools and access".
pub fn plan(root: &Path, home: Option<&Path>, as_instance: bool) -> Vec<PlanRow> {
    let row = |verb: &str, noun: &str, why: &str| PlanRow {
        verb: verb.into(),
        noun: noun.into(),
        why: why.into(),
    };
    let files = ProjectFiles::find(root, home);
    let mut rows = Vec::new();
    if files.root.is_none() && files.folder.is_none() && files.legacy.is_none() {
        rows.push(row(
            "Ask",
            &format!("{} questions", questions(root).len()),
            "what zaf needs to know about this project",
        ));
        rows.push(row(
            "Write",
            ROOT_FILE,
            "your answers, so zaf remembers them",
        ));
    } else if files.legacy.is_some()
        && files.root.is_none()
        && files.folder.is_none()
        && !as_instance
    {
        rows.push(row(
            "Move",
            &format!("{LEGACY_FILE} to {ROOT_FILE}"),
            "the manifest's name now",
        ));
    }
    let project = project_needs_making(root);
    let machine = home.is_some_and(home_needs_making);
    let noun = match (machine, project) {
        (true, true) => Some("~/.zaf and .zaf/"),
        (true, false) => Some("~/.zaf"),
        (false, true) => Some(".zaf/"),
        (false, false) => None,
    };
    if let Some(noun) = noun {
        rows.push(row("Make", noun, "where zaf keeps its state"));
    }
    rows.push(row(
        "Install",
        "the standard actions",
        "the steps zaf runs: open a PR, merge, release",
    ));
    rows.push(row(
        "Check",
        "your tools and access",
        "so the first real run does not fail halfway",
    ));
    rows
}

/// Whether a plan writes into the project or the homes, so the Engineer is asked first.
pub fn writes(rows: &[PlanRow]) -> bool {
    rows.iter()
        .any(|row| WRITING_VERBS.contains(&row.verb.as_str()))
}

/// Whether the project's `.zaf/` lacks a folder or the `.gitignore` allow-list, or holds the
/// old `.gitignore` of `*` that `setup` replaces.
fn project_needs_making(root: &Path) -> bool {
    let state = root.join(STATE_DIR);
    let ignore = state.join(IGNORE_FILE);
    PROJECT_DIRS.iter().any(|dir| !state.join(dir).is_dir())
        || !ignore.is_file()
        || classify_ignore(&ignore).is_ok_and(|kind| kind == IgnoreState::Star)
}

/// Whether the zaf home, its folders or its `config.toml` is missing.
fn home_needs_making(home: &Path) -> bool {
    !home.is_dir()
        || HOME_DIRS.iter().any(|dir| !home.join(dir).is_dir())
        || !home.join(HOME_FILE).is_file()
}

/// What happened to the design repo.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CloneOutcome {
    /// `gh repo clone` ran and succeeded.
    Cloned,
    /// The folder was already there.
    Present,
    /// The clone failed; the message is what it said.
    Failed(String),
}

/// Why `setup` could not finish: a backend failed, not the state refusing.
#[derive(Debug, thiserror::Error)]
pub enum SetupError {
    /// A folder or file could not be made or written.
    #[error(transparent)]
    Io(#[from] io::Error),
    /// The profiles could not be generated: a file, the marketplace or a `claude plugin` command.
    #[error(transparent)]
    Profile(ProfileError),
    /// The pack's actions could not be installed; `replaced` holds what was replaced before.
    #[error("{}", .0.error)]
    Actions(ActionsFailed),
}

/// What `setup` did and what remains.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SetupReport {
    /// What the homes held and what was made.
    pub homes: Homes,
    /// The design repo, when the manifest declares one to clone.
    pub clone: Option<CloneOutcome>,
    /// What the profile generation did; `None` when it refused.
    pub profiles: Option<profile::Report>,
    /// The pack's actions put into the zaf home, and the names already there.
    pub actions: PackActions,
    /// Doctor, run after the folders and the clone.
    pub doctor: Report,
    /// How the board signs in.
    pub board: Backend,
    /// How the forge signs in; `None` with no `[forge]`.
    pub forge: Option<Backend>,
    /// The checks setup itself made that doctor does not: the pack's refusal, the design clone,
    /// the ignore files. Only a failing one is held.
    pub pending: Vec<Check>,
}

impl SetupReport {
    /// Whether nothing is left for the Engineer.
    pub fn is_ready(&self) -> bool {
        self.pending.is_empty() && self.doctor.passed()
    }

    /// Every check setup knows, doctor's and its own: the input of [`fixes`].
    ///
    /// Read it after the board's and the forge's backends are asked, which the caller adds to
    /// [`SetupReport::doctor`].
    pub fn checks(&self) -> Vec<Check> {
        let mut checks: Vec<Check> = self.pending.clone();
        checks.extend(self.doctor.tools.iter().cloned().map(Check::Tool));
        checks.extend(self.doctor.packs.iter().cloned().map(Check::Pack));
        checks.push(Check::Folder(self.doctor.workspaces.clone()));
        checks.push(Check::Folder(self.doctor.actions_dir.clone()));
        checks.extend(self.doctor.board.iter().map(|check| Check::Backend {
            backend: self.board.clone(),
            check: check.clone(),
        }));
        if let Some(backend) = &self.forge {
            checks.extend(self.doctor.forge.iter().map(|check| Check::Backend {
                backend: backend.clone(),
                check: check.clone(),
            }));
        }
        checks
    }

    /// What the Engineer has to do: a [`Fix`] for each failing check.
    pub fn fixes(&self) -> Vec<Fix> {
        fixes(&self.checks())
    }
}

/// The folder in the zaf home that keeps the copy of each action [`install_pack_actions`] replaced.
pub const REPLACED_DIR: &str = "actions-replaced";

/// Who is asked whether an installed action that differs from the pack's is replaced:
/// `trait ReplaceAction { fn replace(&mut self, name: &str, why: Option<&Text>, difference: &str) -> bool; }`.
pub trait ReplaceAction {
    /// Whether the machine's action `name` is replaced by the pack's, given `why`, the pack's
    /// `# changed:` line when the installed copy lacks it, and `difference`, the diff of the two.
    /// Only `true` replaces.
    fn replace(&mut self, name: &str, why: Option<&Text>, difference: &str) -> bool;
}

/// What [`install_pack_actions`] did.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PackActions {
    /// The names copied into the zaf home's `actions/`, sorted.
    pub installed: Vec<String>,
    /// The names the machine tier already had and left as they are, sorted: those that are equal
    /// to the pack's, not a regular file, or differ and were not replaced.
    pub kept: Vec<String>,
    /// Each name replaced by the pack's and where the old copy went, in the order replaced.
    pub replaced: Vec<(String, PathBuf)>,
    /// The names kept though they differ from the pack's, with no one asked: there was no asker, or
    /// the difference could not be shown. Sorted.
    pub differs: Vec<String>,
    /// The names in [`PackActions::differs`] whose difference could not be shown, sorted.
    pub unshown: Vec<String>,
}

impl PackActions {
    /// The lines `setup` prints: one naming what it installed and one naming what it kept; none
    /// for a list that is empty.
    pub fn lines(&self) -> Vec<String> {
        let mut lines = Vec::new();
        if !self.installed.is_empty() {
            lines.push(format!(
                "installed {} pack actions into the machine tier: {}",
                self.installed.len(),
                self.installed.join(", ")
            ));
        }
        for (name, old) in &self.replaced {
            lines.push(format!(
                "replaced {name} (the old one is at {})",
                old.display()
            ));
        }
        if !self.kept.is_empty() {
            lines.push(format!(
                "kept the machine's own, unchanged: {}",
                self.kept.join(", ")
            ));
        }
        let unreviewed: Vec<&str> = self
            .differs
            .iter()
            .filter(|name| !self.unshown.contains(name))
            .map(String::as_str)
            .collect();
        if !unreviewed.is_empty() {
            lines.push(format!(
                "differs from the pack, kept: {}; run zaf setup in a terminal to review",
                unreviewed.join(", ")
            ));
        }
        if !self.unshown.is_empty() {
            lines.push(format!(
                "differs from the pack, kept, and the difference could not be shown: {}",
                self.unshown.join(", ")
            ));
        }
        lines
    }
}

/// How [`install_pack_actions`] failed, with what it had replaced before: the Engineer is still
/// told where each old copy went.
#[derive(Debug)]
pub struct ActionsFailed {
    /// Each name replaced before the failure and where the old copy went, in the order replaced.
    pub replaced: Vec<(String, PathBuf)>,
    /// The failure.
    pub error: io::Error,
}

impl ActionsFailed {
    /// The lines naming what was replaced before the failure, as [`PackActions::lines`] words them.
    pub fn lines(&self) -> Vec<String> {
        PackActions {
            replaced: self.replaced.clone(),
            ..PackActions::default()
        }
        .lines()
    }
}

/// Copies the files of the `actions/` folder of the pack installed in a generated profile that
/// carries it into the zaf `home`'s `actions/`, each name the machine tier lacks, keeping its mode
/// bits. A name already there (a file, a link or anything else) is left byte for byte and listed
/// in [`PackActions::kept`], with one exception: an installed regular file whose bytes or mode bits
/// differ from the pack's is offered to `asker` with the difference `git` shows, and on yes the old
/// file is copied to `actions-replaced/<name>.<UTC time>` in the zaf home and the pack's written
/// over it by a rename. With no asker, or when the difference cannot be shown, it is kept and
/// listed in [`PackActions::differs`]. A link or a folder is never offered. Nothing is deleted.
/// Only regular files of the pack are used: a link, a folder (`hooks/` included) and a name an
/// action may not have are skipped. Installs nothing without a home, a pack, an installed pack or
/// a pack with no `actions/`.
fn install_pack_actions(
    root: &Path,
    state_dir: &Path,
    home: Option<&Path>,
    manifest: &Manifest,
    commands: &dyn Commands,
    asker: Option<&mut dyn ReplaceAction>,
    now: SystemTime,
) -> Result<PackActions, ActionsFailed> {
    let mut done = PackActions::default();
    match install_into(
        &mut done, root, state_dir, home, manifest, commands, asker, now,
    ) {
        Ok(()) => Ok(done),
        Err(error) => Err(ActionsFailed {
            replaced: done.replaced,
            error,
        }),
    }
}

/// The work of [`install_pack_actions`], recording into `done` as it goes, so a failure leaves
/// there what was done before it.
#[allow(clippy::too_many_arguments)]
fn install_into(
    done: &mut PackActions,
    root: &Path,
    state_dir: &Path,
    home: Option<&Path>,
    manifest: &Manifest,
    commands: &dyn Commands,
    asker: Option<&mut dyn ReplaceAction>,
    now: SystemTime,
) -> io::Result<()> {
    let Some(home) = home else {
        return Ok(());
    };
    let Some(pack) = manifest
        .pack
        .as_ref()
        .and_then(|pack| profile::pack_ref(root, pack).ok().flatten())
    else {
        return Ok(());
    };
    let Some(profile) = profile::generated(manifest)
        .into_iter()
        .find(|profile| profile::carries_pack(*profile))
    else {
        return Ok(());
    };
    let profile_home = profile::home(state_dir, profile);
    let Some(installed) = profile::installed_path(&profile_home, &pack.to_string()) else {
        return Ok(());
    };
    install_from(
        done,
        &installed.join(ACTIONS_DIR),
        home,
        commands,
        asker,
        now,
    )
}

/// The regular files of the pack's `actions/` folder whose names an action may have, sorted by
/// name; none when the folder cannot be read.
fn pack_files(pack_actions: &Path) -> io::Result<Vec<(String, PathBuf)>> {
    let Ok(entries) = fs::read_dir(pack_actions) else {
        return Ok(Vec::new());
    };
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    for entry in entries {
        let entry = entry?;
        let Ok(name) = entry.file_name().into_string() else {
            continue;
        };
        let path = entry.path();
        if check_name(&name).is_ok() && fs::symlink_metadata(&path)?.is_file() {
            files.push((name, path));
        }
    }
    files.sort();
    Ok(files)
}

/// The loop [`install_pack_actions`] and [`install_machine_actions`] share: installs the files of
/// `pack_actions` into the zaf `home`'s `actions/`, recording into `done` as it goes.
fn install_from(
    done: &mut PackActions,
    pack_actions: &Path,
    home: &Path,
    commands: &dyn Commands,
    mut asker: Option<&mut dyn ReplaceAction>,
    now: SystemTime,
) -> io::Result<()> {
    let target = home.join(ACTIONS_DIR);
    for (name, path) in pack_files(pack_actions)? {
        fs::create_dir_all(&target)?;
        if copy_new(&path, &target, &name)? {
            done.installed.push(name);
            continue;
        }
        let installed = target.join(&name);
        // A link, a folder or anything but a regular file is never offered.
        if !fs::symlink_metadata(&installed)?.is_file() || !differs(&installed, &path)? {
            done.kept.push(name);
            continue;
        }
        let Some(asker) = asker.as_deref_mut() else {
            done.differs.push(name.clone());
            done.kept.push(name);
            continue;
        };
        let Some(shown) = difference(commands, &installed, &path) else {
            done.unshown.push(name.clone());
            done.differs.push(name.clone());
            done.kept.push(name);
            continue;
        };
        let reason = match (fs::read_to_string(&installed), fs::read_to_string(&path)) {
            (Ok(held), Ok(offered)) => why(&held, &offered),
            _ => None,
        };
        if asker.replace(&name, reason.as_ref(), &shown) {
            let old = keep_old_copy(&installed, &home.join(REPLACED_DIR), &name, now)?;
            replace_with(&path, &target, &name)?;
            done.replaced.push((name, old));
        } else {
            done.kept.push(name);
        }
    }
    Ok(())
}

/// [`install_pack_actions`] for a folder the caller names: the files of `pack_actions` (the
/// `actions/` folder of an installed pack) go into the zaf `home`'s `actions/` as setup's do, each
/// differing one offered to `asker` with its why (the pack's `# changed:` line, when the installed
/// copy lacks it) and its difference. Old copies go to `actions-replaced/`; nothing is deleted.
pub fn install_machine_actions(
    home: &Path,
    pack_actions: &Path,
    commands: &dyn Commands,
    asker: Option<&mut dyn ReplaceAction>,
    now: SystemTime,
) -> Result<PackActions, ActionsFailed> {
    let mut done = PackActions::default();
    match install_from(&mut done, pack_actions, home, commands, asker, now) {
        Ok(()) => Ok(done),
        Err(error) => Err(ActionsFailed {
            replaced: done.replaced,
            error,
        }),
    }
}

/// The names in `pack_actions` that are new to the zaf `home`'s `actions/` or that differ from the
/// installed regular file (bytes or mode bits), sorted, and the number of actions the pack has.
/// Changes nothing; a file that cannot be read is not counted as changed.
pub fn changed_actions(home: &Path, pack_actions: &Path) -> (Vec<String>, usize) {
    let files = pack_files(pack_actions).unwrap_or_default();
    let target = home.join(ACTIONS_DIR);
    let changed = files
        .iter()
        .filter(|(name, path)| {
            let installed = target.join(name);
            match fs::symlink_metadata(&installed) {
                Err(error) => error.kind() == io::ErrorKind::NotFound,
                Ok(meta) => meta.is_file() && differs(&installed, path).unwrap_or(false),
            }
        })
        .map(|(name, _)| name.clone())
        .collect();
    (changed, files.len())
}

/// Copies `installed`, with its mode bits, to a new file `<dir>/<name>.<UTC time>` (as
/// `20261118T091500Z`), making `dir`; a name already taken gets `.1`, `.2` and so on after it, so
/// nothing is overwritten. Returns where the copy is.
fn keep_old_copy(installed: &Path, dir: &Path, name: &str, now: SystemTime) -> io::Result<PathBuf> {
    fs::create_dir_all(dir)?;
    let time = humantime::format_rfc3339_seconds(now)
        .to_string()
        .replace(['-', ':'], "");
    let mode = fs::metadata(installed)?.permissions().mode() & 0o777;
    let bytes = fs::read(installed)?;
    for attempt in 0_u32.. {
        let file = if attempt == 0 {
            format!("{name}.{time}")
        } else {
            format!("{name}.{time}.{attempt}")
        };
        let path = dir.join(file);
        let mut copy = match OpenOptions::new().write(true).create_new(true).open(&path) {
            Ok(copy) => copy,
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(error) => return Err(error),
        };
        copy.write_all(&bytes)?;
        copy.set_permissions(fs::Permissions::from_mode(mode))?;
        copy.sync_all()?;
        return Ok(path);
    }
    unreachable!("the attempts are not bounded")
}

/// Puts `source`, with its mode bits, at `<dir>/<name>` over whatever is there: the bytes go to a
/// temporary file first, which is renamed over the name, so a reader never sees half a file.
fn replace_with(source: &Path, dir: &Path, name: &str) -> io::Result<()> {
    let temporary = write_temporary(source, dir, name)?;
    let renamed = fs::rename(&temporary, dir.join(name));
    if renamed.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    renamed
}

/// Writes `source`, with its mode bits, to a new temporary file in `dir`; returns its path.
fn write_temporary(source: &Path, dir: &Path, name: &str) -> io::Result<PathBuf> {
    let mode = fs::metadata(source)?.permissions().mode() & 0o777;
    let temporary = dir.join(format!(".{name}.zaf-installing"));
    match fs::remove_file(&temporary) {
        Ok(()) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    let written = (|| {
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary)?;
        file.write_all(&fs::read(source)?)?;
        file.set_permissions(fs::Permissions::from_mode(mode))?;
        file.sync_all()
    })();
    if let Err(error) = written {
        let _ = fs::remove_file(&temporary);
        return Err(error);
    }
    Ok(temporary)
}

/// Copies `source` to `<dir>/<name>` with its mode bits unless something is there; whether it did.
/// The bytes go to a temporary file first and are linked into place, which fails when the name
/// exists, so a reader never sees half a file and a name made meanwhile is never replaced.
fn copy_new(source: &Path, dir: &Path, name: &str) -> io::Result<bool> {
    let target = dir.join(name);
    if fs::symlink_metadata(&target).is_ok() {
        return Ok(false);
    }
    let temporary = write_temporary(source, dir, name)?;
    let linked = match fs::hard_link(&temporary, &target) {
        Ok(()) => Ok(true),
        Err(error) if error.kind() == io::ErrorKind::AlreadyExists => Ok(false),
        Err(error) => Err(error),
    };
    let _ = fs::remove_file(&temporary);
    linked
}

/// Whether the installed action at `installed` differs from the pack's at `pack`: in its bytes or
/// in its mode bits (the nine permission bits `copy_new` keeps). The comparison is made here, on
/// the bytes and the mode, and never by `git`. Either file missing is an error.
fn differs(installed: &Path, pack: &Path) -> io::Result<bool> {
    let installed_mode = fs::metadata(installed)?.permissions().mode() & 0o777;
    let pack_mode = fs::metadata(pack)?.permissions().mode() & 0o777;
    if installed_mode != pack_mode {
        return Ok(true);
    }
    Ok(fs::read(installed)? != fs::read(pack)?)
}

/// The difference between an installed action and the pack's as `git diff --no-index` prints it,
/// asked through `commands`. Only the text is returned, and only when it opens with `diff --git`:
/// a missing `git`, a failure to start it or any other output is none. `git` shows the difference
/// and never decides it (see [`differs`]); it exits 1 when files differ, so its exit status is not
/// read.
fn difference(commands: &dyn Commands, installed: &Path, pack: &Path) -> Option<String> {
    let installed = installed.to_string_lossy();
    let pack = pack.to_string_lossy();
    let output = commands
        .run(
            "git",
            &[
                "diff",
                "--no-index",
                "--no-ext-diff",
                "--no-color",
                "--",
                &installed,
                &pack,
            ],
        )
        .ok()?;
    output.text.starts_with("diff --git").then_some(output.text)
}

fn clone_design(root: &Path, manifest: &Manifest, commands: &dyn Commands) -> Option<CloneOutcome> {
    if manifest.design.kind != DesignKind::GitSibling {
        return None;
    }
    let repo = manifest.design.repo.as_ref()?;
    let dir = design_dir(root, &manifest.design)?;
    if dir.is_dir() {
        return Some(CloneOutcome::Present);
    }
    let target = dir.to_string_lossy();
    let outcome = match commands.run("gh", &["repo", "clone", repo.as_ref(), &target]) {
        Ok(output) if output.success => CloneOutcome::Cloned,
        Ok(output) => CloneOutcome::Failed(output.text.trim().to_owned()),
        Err(error) => CloneOutcome::Failed(error.to_string()),
    };
    Some(outcome)
}

/// The checks setup makes itself, those that fail: the pack's refusal, the design clone and the
/// two ignore files. Doctor's own are read from its report ([`SetupReport::checks`]).
fn pending(
    manifest: &Manifest,
    root: &Path,
    clone: Option<&CloneOutcome>,
    refusal: Option<&ProfileError>,
    homes: &Homes,
) -> Vec<Check> {
    let mut checks = Vec::new();
    if let Some(refusal) = refusal {
        checks.push(Check::PackRefused(refusal.to_string()));
    }
    if let (Some(CloneOutcome::Failed(said)), Some(repo), Some(dir)) = (
        clone,
        manifest.design.repo.as_ref(),
        design_dir(root, &manifest.design),
    ) {
        checks.push(Check::CloneFailed {
            repo: repo.to_string(),
            dir: dir.display().to_string(),
            said: said.clone(),
        });
    }
    if homes.ignore == Some(IgnoreState::Foreign) {
        checks.push(Check::IgnoreForeign {
            lines: IGNORE_LINES.iter().map(|line| (*line).to_owned()).collect(),
            file: format!("{STATE_DIR}/{IGNORE_FILE}"),
        });
    }
    if root_ignores_state_dir(root) {
        checks.push(Check::RootIgnoresState {
            folder: STATE_DIR.to_owned(),
        });
    }
    checks
}

/// How the board signs in, from the manifest.
fn board_backend(manifest: &Manifest) -> Backend {
    match manifest.board.kind {
        BoardKind::GithubIssues | BoardKind::GithubProjects => Backend::Github,
        BoardKind::ForgejoIssues => Backend::Forgejo {
            token_env: manifest.board.token_env().to_string(),
        },
    }
}

/// How the forge signs in, from the manifest; `None` with no `[forge]`.
fn forge_backend(manifest: &Manifest) -> Option<Backend> {
    manifest.forge.as_ref().map(|forge| match forge.kind {
        ForgeKind::Github => Backend::Github,
        ForgeKind::Forgejo => Backend::Forgejo {
            token_env: forge.token_env().to_string(),
        },
    })
}

/// Ensures both homes, replaces an old `.zaf/.gitignore` that holds only `*`, clones a declared
/// design repo that is missing, generates the manifest's profiles through `shell` as
/// `zaf profile init` does and runs doctor; [`SetupReport::fixes`] turns what failed into fixes.
/// Idempotent.
///
/// A refusal of the generation is a fix; any other failure of it is an error. An
/// installed action that differs from the pack's is replaced only when `asker` says yes; with
/// none, no one can be asked and it is kept.
pub fn setup(
    root: &Path,
    home: Option<&Path>,
    manifest: &Manifest,
    commands: &dyn Commands,
    shell: &dyn Shell,
    asker: Option<&mut dyn ReplaceAction>,
) -> Result<SetupReport, SetupError> {
    let claude_home = profile::claude_home();
    setup_with(
        root,
        home,
        manifest,
        commands,
        shell,
        claude_home.as_deref(),
        asker,
    )
}

/// [`setup`] against a given Claude home; `None`, when there is none, links nothing.
fn setup_with(
    root: &Path,
    home: Option<&Path>,
    manifest: &Manifest,
    commands: &dyn Commands,
    shell: &dyn Shell,
    claude_home: Option<&Path>,
    asker: Option<&mut dyn ReplaceAction>,
) -> Result<SetupReport, SetupError> {
    let mut homes = ensure_homes(Some(root), home)?;
    if homes.ignore == Some(IgnoreState::Star) {
        fs::write(root.join(STATE_DIR).join(IGNORE_FILE), ignore_text())?;
        homes.ignore = Some(IgnoreState::Replaced);
    }
    let clone = clone_design(root, manifest, commands);
    let state_dir = root.join(STATE_DIR);
    let (profiles, refusal) =
        match profile::init_with(root, &state_dir, manifest, shell, claude_home) {
            Ok(profiles) => (Some(profiles), None),
            Err(error) if error.is_refusal() => (None, Some(error)),
            Err(error) => return Err(SetupError::Profile(error)),
        };
    let actions = if profiles.is_some() {
        install_pack_actions(
            root,
            &state_dir,
            home,
            manifest,
            commands,
            asker,
            SystemTime::now(),
        )
        .map_err(SetupError::Actions)?
    } else {
        PackActions::default()
    };
    let report = doctor_with(
        root,
        home,
        manifest,
        commands,
        claude_home,
        SystemTime::now(),
    );
    let pending = pending(manifest, root, clone.as_ref(), refusal.as_ref(), &homes);
    Ok(SetupReport {
        homes,
        clone,
        profiles,
        actions,
        doctor: report,
        board: board_backend(manifest),
        forge: forge_backend(manifest),
        pending,
    })
}

